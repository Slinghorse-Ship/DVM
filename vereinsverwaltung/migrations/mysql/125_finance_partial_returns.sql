 CHECK(JSON_VALID(request_json) AND JSON_VALID(review_json) AND JSON_VALID(result_json)),
 CHECK((version=1 AND voided_at IS NULL AND voided_by IS NULL AND void_reason='' AND void_request_key IS NULL AND void_json IS NULL AND void_sha256 IS NULL) OR (version=2 AND voided_at IS NOT NULL AND voided_by IS NOT NULL AND CHAR_LENGTH(TRIM(void_reason))>0 AND void_request_key IS NOT NULL AND JSON_VALID(void_json) AND void_sha256 IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS finance_transfer_settlement_items (
 club_id VARCHAR(128) NOT NULL,
 id CHAR(32) NOT NULL,
 settlement_id CHAR(32) NOT NULL,
 allocation_id VARCHAR(128) NOT NULL,
 source_id VARCHAR(128) NOT NULL,
 entry_id VARCHAR(128) NOT NULL,
 cents BIGINT NOT NULL,
 released_at VARCHAR(40) DEFAULT NULL,
 active_allocation_id VARCHAR(128) GENERATED ALWAYS AS (IF(released_at IS NULL,allocation_id,NULL)) STORED,
 PRIMARY KEY(club_id,id),
 UNIQUE KEY transfer_settlement_allocation(club_id,settlement_id,allocation_id),
 UNIQUE KEY transfer_settlement_active_allocation(club_id,active_allocation_id),
 KEY transfer_settlement_source(club_id,source_id,released_at),
 FOREIGN KEY(club_id,settlement_id) REFERENCES finance_transfer_settlements(club_id,id),
 FOREIGN KEY(club_id,allocation_id) REFERENCES finance_allocations(club_id,id),
 FOREIGN KEY(club_id,source_id) REFERENCES finance_transactions(club_id,id),
 FOREIGN KEY(club_id,entry_id) REFERENCES finance_entries(club_id,id),
 CHECK(cents>0 AND cents<=100000000000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

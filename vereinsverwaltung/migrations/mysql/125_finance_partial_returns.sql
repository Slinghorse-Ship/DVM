CREATE TABLE IF NOT EXISTS finance_allocation_funding (
 club_id VARCHAR(128) NOT NULL,
 allocation_id VARCHAR(128) NOT NULL,
 source_id VARCHAR(128) NOT NULL,
 entry_id VARCHAR(128) NOT NULL,
 cents BIGINT NOT NULL,
 face_cents BIGINT NOT NULL,
 ranges_json LONGTEXT NOT NULL,
 ranges_sha256 CHAR(64) NOT NULL,
 created_by VARCHAR(128) NOT NULL,
 created_at VARCHAR(40) NOT NULL,
 original_json LONGTEXT NOT NULL,
 original_sha256 CHAR(64) NOT NULL,
 PRIMARY KEY(club_id,allocation_id),
 KEY funding_entry(club_id,entry_id),
 FOREIGN KEY(club_id,allocation_id) REFERENCES finance_allocations(club_id,id),
 FOREIGN KEY(club_id,source_id) REFERENCES finance_transactions(club_id,id),
 FOREIGN KEY(club_id,entry_id) REFERENCES finance_entries(club_id,id),
 CHECK(cents>0 AND cents<=face_cents AND face_cents<=100000000000),
 CHECK(JSON_VALID(ranges_json) AND JSON_VALID(original_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS finance_partial_returns (
 club_id VARCHAR(128) NOT NULL,
 id CHAR(32) NOT NULL,
 counter_id VARCHAR(128) NOT NULL,
 cents BIGINT NOT NULL,
 reason VARCHAR(500) NOT NULL,
 request_key CHAR(32) NOT NULL,
 created_by VARCHAR(128) NOT NULL,
 created_at VARCHAR(40) NOT NULL,
 request_json LONGTEXT NOT NULL,
 request_sha256 CHAR(64) NOT NULL,
 review_json LONGTEXT NOT NULL,
 review_sha256 CHAR(64) NOT NULL,
 result_json LONGTEXT NOT NULL,
 result_sha256 CHAR(64) NOT NULL,
 version INTEGER NOT NULL DEFAULT 1,
 voided_at VARCHAR(40) DEFAULT NULL,
 voided_by VARCHAR(128) DEFAULT NULL,
 void_reason VARCHAR(500) NOT NULL DEFAULT '',
 void_request_key CHAR(32) DEFAULT NULL,
 void_json LONGTEXT DEFAULT NULL,
 void_sha256 CHAR(64) DEFAULT NULL,
 PRIMARY KEY(club_id,id),
 UNIQUE KEY partial_return_request(club_id,request_key),
 UNIQUE KEY partial_return_void_request(club_id,void_request_key),
 KEY partial_return_counter(club_id,counter_id,voided_at),
 FOREIGN KEY(club_id,counter_id) REFERENCES finance_transactions(club_id,id),
 CHECK(cents>0 AND cents<=100000000000),
 CHECK(JSON_VALID(request_json) AND JSON_VALID(review_json) AND JSON_VALID(result_json)),
 CHECK((version=1 AND voided_at IS NULL AND voided_by IS NULL AND void_reason='' AND void_request_key IS NULL AND void_json IS NULL AND void_sha256 IS NULL) OR (version=2 AND voided_at IS NOT NULL AND voided_by IS NOT NULL AND CHAR_LENGTH(TRIM(void_reason))>0 AND void_request_key IS NOT NULL AND JSON_VALID(void_json) AND void_sha256 IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS finance_partial_return_items (
 club_id VARCHAR(128) NOT NULL,
 id CHAR(32) NOT NULL,
 return_id CHAR(32) NOT NULL,
 allocation_id VARCHAR(128) NOT NULL,
 source_id VARCHAR(128) NOT NULL,
 entry_id VARCHAR(128) NOT NULL,
 ordinal SMALLINT NOT NULL,
 cents BIGINT NOT NULL,
 ranges_json LONGTEXT NOT NULL,
 ranges_sha256 CHAR(64) NOT NULL,
 PRIMARY KEY(club_id,id),
 UNIQUE KEY partial_return_allocation(club_id,return_id,allocation_id),
 UNIQUE KEY partial_return_ordinal(club_id,return_id,ordinal),
 KEY partial_return_original(club_id,allocation_id),
 KEY partial_return_source(club_id,source_id),
 KEY partial_return_entry(club_id,entry_id),
 FOREIGN KEY(club_id,return_id) REFERENCES finance_partial_returns(club_id,id),
 FOREIGN KEY(club_id,allocation_id) REFERENCES finance_allocation_funding(club_id,allocation_id),
 FOREIGN KEY(club_id,source_id) REFERENCES finance_transactions(club_id,id),
 FOREIGN KEY(club_id,entry_id) REFERENCES finance_entries(club_id,id),
 CHECK(ordinal BETWEEN 1 AND 40 AND cents>0 AND cents<=100000000000),
 CHECK(JSON_VALID(ranges_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS finance_transfer_settlements (
 club_id VARCHAR(128) NOT NULL,
 id CHAR(32) NOT NULL,
 order_id VARCHAR(128) NOT NULL,
 reason VARCHAR(500) NOT NULL,
 evidence VARCHAR(2000) NOT NULL,
 request_key CHAR(32) NOT NULL,
 created_by VARCHAR(128) NOT NULL,
 created_at VARCHAR(40) NOT NULL,
 request_json LONGTEXT NOT NULL,
 request_sha256 CHAR(64) NOT NULL,
 review_json LONGTEXT NOT NULL,
 review_sha256 CHAR(64) NOT NULL,
 result_json LONGTEXT NOT NULL,
 result_sha256 CHAR(64) NOT NULL,
 version INTEGER NOT NULL DEFAULT 1,
 voided_at VARCHAR(40) DEFAULT NULL,
 voided_by VARCHAR(128) DEFAULT NULL,
 void_reason VARCHAR(500) NOT NULL DEFAULT '',
 void_request_key CHAR(32) DEFAULT NULL,
 void_json LONGTEXT DEFAULT NULL,
 void_sha256 CHAR(64) DEFAULT NULL,
 active_order_id VARCHAR(128) GENERATED ALWAYS AS (IF(voided_at IS NULL,order_id,NULL)) STORED,

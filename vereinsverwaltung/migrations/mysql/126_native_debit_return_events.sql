CREATE TABLE IF NOT EXISTS finance_native_return_events (
 club_id VARCHAR(128) NOT NULL,
 id CHAR(32) NOT NULL,
 item_id VARCHAR(128) NOT NULL,
 order_id VARCHAR(128) NOT NULL,
 ordinal BIGINT NOT NULL,
 kind VARCHAR(24) NOT NULL,
 after_event_id CHAR(32) DEFAULT NULL,
 parent_return_id VARCHAR(128) DEFAULT NULL,
 counter_id VARCHAR(128) NOT NULL,
 document_id VARCHAR(128) DEFAULT NULL,
 financial_id CHAR(32) DEFAULT NULL,
 financial_request_key CHAR(32) DEFAULT NULL,
 legacy_source_id VARCHAR(128) DEFAULT NULL,
 native_request_key CHAR(32) NOT NULL,
 created_by VARCHAR(128) NOT NULL,
 created_at VARCHAR(40) NOT NULL,
 request_json LONGTEXT NOT NULL,
 request_sha256 CHAR(64) NOT NULL,
 review_json LONGTEXT NOT NULL,
 review_sha256 CHAR(64) NOT NULL,
 result_json LONGTEXT NOT NULL,
 result_sha256 CHAR(64) NOT NULL,
 PRIMARY KEY(club_id,id),
 UNIQUE KEY native_return_event_ordinal(club_id,item_id,ordinal),
 UNIQUE KEY native_return_event_request(club_id,native_request_key),
 KEY native_return_event_order(club_id,order_id,ordinal),
 KEY native_return_event_financial(club_id,financial_id,kind),
 KEY native_return_event_parent(club_id,parent_return_id,kind),
 FOREIGN KEY(club_id,item_id) REFERENCES sepa_order_items(club_id,id),
 FOREIGN KEY(club_id,order_id) REFERENCES sepa_orders(club_id,id),
 FOREIGN KEY(club_id,counter_id) REFERENCES finance_transactions(club_id,id),
 FOREIGN KEY(club_id,document_id) REFERENCES documents(club_id,id),
 FOREIGN KEY(club_id,legacy_source_id) REFERENCES finance_transactions(club_id,id),
 CHECK(ordinal>0 AND ordinal<=1000000),
 CHECK(kind IN ('return','attach','attach_existing','undo')),
 CHECK((ordinal=1 AND after_event_id IS NULL) OR (ordinal>1 AND after_event_id IS NOT NULL)),
 CHECK((kind='return') OR parent_return_id IS NOT NULL),
 CHECK((financial_id IS NULL AND financial_request_key IS NULL) OR (financial_id IS NOT NULL AND financial_request_key IS NOT NULL)),
 CHECK(JSON_VALID(request_json) AND JSON_VALID(review_json) AND JSON_VALID(result_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS finance_payment_returns (
 club_id VARCHAR(128) NOT NULL,
 id CHAR(32) NOT NULL,
 source_id VARCHAR(128) NOT NULL,
 returned_id VARCHAR(128) NOT NULL,
 cents BIGINT NOT NULL,
 reason VARCHAR(500) NOT NULL,
 request_key CHAR(32) NOT NULL,
 created_by VARCHAR(128) NOT NULL,
 created_at VARCHAR(40) NOT NULL,
 request_json LONGTEXT NOT NULL,
 request_sha256 CHAR(64) NOT NULL,
 review_json LONGTEXT NOT NULL,
 review_sha256 CHAR(64) NOT NULL,
 result_json LONGTEXT NOT NULL,
 result_sha256 CHAR(64) NOT NULL,
 PRIMARY KEY(club_id,id),
 UNIQUE KEY payment_return_request(club_id,request_key),
 UNIQUE KEY payment_return_source(club_id,source_id),
 UNIQUE KEY payment_return_returned(club_id,returned_id),
 FOREIGN KEY(club_id,source_id) REFERENCES finance_transactions(club_id,id),
 FOREIGN KEY(club_id,returned_id) REFERENCES finance_transactions(club_id,id),
 CHECK(cents>0 AND source_id<>returned_id),
 CHECK(JSON_VALID(request_json) AND JSON_VALID(review_json) AND JSON_VALID(result_json))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

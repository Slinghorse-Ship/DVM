CREATE TABLE IF NOT EXISTS finance_payment_return_order_links (
 club_id VARCHAR(128) NOT NULL,
 id CHAR(32) NOT NULL,
 return_id CHAR(32) NOT NULL,
 order_id VARCHAR(128) NOT NULL,
 request_key CHAR(32) NOT NULL,
 reason VARCHAR(500) NOT NULL,
 evidence VARCHAR(2000) NOT NULL,
 created_by VARCHAR(128) NOT NULL,
 created_at VARCHAR(40) NOT NULL,
 request_json LONGTEXT NOT NULL,
 request_sha256 CHAR(64) NOT NULL,
 review_json LONGTEXT NOT NULL,
 review_sha256 CHAR(64) NOT NULL,
 result_json LONGTEXT NOT NULL,
 result_sha256 CHAR(64) NOT NULL,
 version INTEGER NOT NULL DEFAULT 1,
 voided_at VARCHAR(40) DEFAULT NULL,
 voided_by VARCHAR(128) DEFAULT NULL,
 void_reason VARCHAR(500) NOT NULL DEFAULT '',
 void_request_key CHAR(32) DEFAULT NULL,
 void_json LONGTEXT DEFAULT NULL,
 void_sha256 CHAR(64) DEFAULT NULL,
 active_order_id VARCHAR(128) GENERATED ALWAYS AS (IF(voided_at IS NULL,order_id,NULL)) STORED,
 PRIMARY KEY(club_id,id),
 UNIQUE KEY return_order_request(club_id,request_key),
 UNIQUE KEY return_order_active(club_id,active_order_id),
 UNIQUE KEY return_order_void_request(club_id,void_request_key),
 KEY return_order_history(club_id,return_id,created_at),
 FOREIGN KEY(club_id,return_id) REFERENCES finance_payment_returns(club_id,id),
 FOREIGN KEY(club_id,order_id) REFERENCES finance_transfer_orders(club_id,id),
 CHECK(JSON_VALID(request_json) AND JSON_VALID(review_json) AND JSON_VALID(result_json)),
 CHECK((version=1 AND voided_at IS NULL AND voided_by IS NULL AND void_reason='' AND void_request_key IS NULL AND void_json IS NULL AND void_sha256 IS NULL) OR (version=2 AND voided_at IS NOT NULL AND voided_by IS NOT NULL AND CHAR_LENGTH(TRIM(void_reason))>0 AND void_request_key IS NOT NULL AND JSON_VALID(void_json) AND void_sha256 IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS goods_donation_corrections (
 club_id VARCHAR(128) NOT NULL,
 id CHAR(32) NOT NULL,
 goods_id VARCHAR(128) NOT NULL,
 source_version INT NOT NULL,
 result_version INT NOT NULL,
 request_key CHAR(32) NOT NULL,
 actor_id VARCHAR(128) NOT NULL,
 happened_at VARCHAR(40) NOT NULL,
 reason TEXT NOT NULL,
 request_json LONGTEXT NOT NULL,
 request_sha256 CHAR(64) NOT NULL,
 review_sha256 CHAR(64) NOT NULL,
 previous_source LONGTEXT NOT NULL,
 next_source LONGTEXT NOT NULL,
 previous_positions LONGTEXT NOT NULL,
 next_positions LONGTEXT NOT NULL,
 PRIMARY KEY(club_id,id),
 UNIQUE KEY goods_correction_request(club_id,request_key),
 UNIQUE KEY goods_correction_version(club_id,goods_id,result_version),
 FOREIGN KEY(club_id,goods_id) REFERENCES goods_donations(club_id,id),
 CHECK(source_version>0 AND result_version=source_version+1),
 CHECK(JSON_VALID(request_json) AND JSON_VALID(previous_source) AND JSON_VALID(next_source) AND JSON_VALID(previous_positions) AND JSON_VALID(next_positions))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

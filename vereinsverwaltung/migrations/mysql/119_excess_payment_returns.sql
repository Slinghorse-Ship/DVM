CREATE TABLE IF NOT EXISTS finance_excess_returns (
 club_id VARCHAR(128) NOT NULL,
 id CHAR(32) NOT NULL,
 source_id VARCHAR(128) NOT NULL,
 returned_id VARCHAR(128) NOT NULL,
 cents BIGINT NOT NULL,
 reason VARCHAR(500) NOT NULL,
 request_key CHAR(32) NOT NULL,
 created_by VARCHAR(128) NOT NULL,
 created_at VARCHAR(40) NOT NULL,
 request_json LONGTEXT NOT NULL,
 request_sha256 CHAR(64) NOT NULL,
 review_json LONGTEXT NOT NULL,
 review_sha256 CHAR(64) NOT NULL,
 version INT NOT NULL DEFAULT 1,
 voided_at VARCHAR(40) NULL,
 void_reason VARCHAR(500) NULL,
 voided_by VARCHAR(128) NULL,
 PRIMARY KEY(club_id,id),
 UNIQUE KEY excess_return_request(club_id,request_key),
 KEY excess_return_source(club_id,source_id),
 KEY excess_return_counter(club_id,returned_id),
 FOREIGN KEY(club_id,source_id) REFERENCES finance_transactions(club_id,id),
 FOREIGN KEY(club_id,returned_id) REFERENCES finance_transactions(club_id,id),
 CHECK(cents>0 AND source_id<>returned_id),
 CHECK(JSON_VALID(request_json) AND JSON_VALID(review_json)),
 CHECK((voided_at IS NULL AND void_reason IS NULL AND voided_by IS NULL AND version=1)
  OR (voided_at IS NOT NULL AND void_reason IS NOT NULL AND voided_by IS NOT NULL AND version=2))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

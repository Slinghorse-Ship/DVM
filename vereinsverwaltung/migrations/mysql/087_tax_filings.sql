-- Additive ELSTER workspace. Existing accounting, documents and members are untouched.
CREATE TABLE IF NOT EXISTS tax_filing_profiles (
 club_id varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL,
 tax_year int NOT NULL,
 version int NOT NULL DEFAULT 1,
 answers mediumtext COLLATE utf8mb4_unicode_ci NOT NULL,
 updated_by varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL,
 updated_at varchar(40) COLLATE utf8mb4_unicode_ci NOT NULL,
 PRIMARY KEY(club_id,tax_year),
 CONSTRAINT tax_profile_club FOREIGN KEY(club_id) REFERENCES clubs(id),
 CONSTRAINT tax_profile_json CHECK(JSON_VALID(answers)),
 CONSTRAINT tax_profile_version CHECK(version>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS tax_filings (
 club_id varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL,
 id varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL,
 family varchar(40) COLLATE utf8mb4_unicode_ci NOT NULL,
 data_version varchar(80) COLLATE utf8mb4_unicode_ci NOT NULL,
 tax_year int NOT NULL,
 environment varchar(12) COLLATE utf8mb4_unicode_ci NOT NULL,
 state varchar(24) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'draft',
 version int NOT NULL DEFAULT 1,
 form_data mediumtext COLLATE utf8mb4_unicode_ci NOT NULL,
 scope_snapshot mediumtext COLLATE utf8mb4_unicode_ci NOT NULL,
 xml_data mediumtext COLLATE utf8mb4_unicode_ci NULL,
 xml_sha256 char(64) COLLATE utf8mb4_unicode_ci NULL,
 content_sha256 char(64) COLLATE utf8mb4_unicode_ci NULL,
 runtime_sha256 char(64) COLLATE utf8mb4_unicode_ci NULL,
 validation mediumtext COLLATE utf8mb4_unicode_ci NULL,
 pdf mediumblob NULL,
 created_by varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL,
 updated_by varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL,
 created_at varchar(40) COLLATE utf8mb4_unicode_ci NOT NULL,
 updated_at varchar(40) COLLATE utf8mb4_unicode_ci NOT NULL,
 PRIMARY KEY(club_id,id),
 CONSTRAINT tax_filing_club FOREIGN KEY(club_id) REFERENCES clubs(id),
 CONSTRAINT tax_filing_form CHECK(JSON_VALID(form_data)),
 CONSTRAINT tax_filing_scope CHECK(JSON_VALID(scope_snapshot)),
 CONSTRAINT tax_filing_validation CHECK(validation IS NULL OR JSON_VALID(validation)),
 CONSTRAINT tax_filing_environment CHECK(environment IN ('test','production')),
 CONSTRAINT tax_filing_state CHECK(state IN ('draft','validated','sending','sent_test','sent_production','failed','unknown')),
 CONSTRAINT tax_filing_version CHECK(version>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS tax_filing_attempts (
 club_id varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL,
 id varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL,
 filing_id varchar(32) COLLATE utf8mb4_unicode_ci NOT NULL,
 request_key varchar(64) COLLATE utf8mb4_unicode_ci NOT NULL,
 environment varchar(12) COLLATE utf8mb4_unicode_ci NOT NULL,
 xml_sha256 char(64) COLLATE utf8mb4_unicode_ci NOT NULL,
 content_sha256 char(64) COLLATE utf8mb4_unicode_ci NOT NULL,
 approved_by varchar(128) COLLATE utf8mb4_unicode_ci NOT NULL,
 started_at varchar(40) COLLATE utf8mb4_unicode_ci NOT NULL,
 completed_at varchar(40) COLLATE utf8mb4_unicode_ci NULL,
 state varchar(24) COLLATE utf8mb4_unicode_ci NOT NULL,
 dedupe_sha256 char(64) COLLATE utf8mb4_unicode_ci GENERATED ALWAYS AS (CASE WHEN state='failed' THEN NULL ELSE content_sha256 END) STORED,
 response mediumtext COLLATE utf8mb4_unicode_ci NULL,
 transfer_ticket varchar(256) COLLATE utf8mb4_unicode_ci NULL,
 pdf mediumblob NULL,
 PRIMARY KEY(club_id,id),
 UNIQUE KEY tax_request_key(club_id,request_key),
 UNIQUE KEY tax_once_per_content(club_id,environment,dedupe_sha256),
 CONSTRAINT tax_attempt_filing FOREIGN KEY(club_id,filing_id) REFERENCES tax_filings(club_id,id),
 CONSTRAINT tax_attempt_response CHECK(response IS NULL OR JSON_VALID(response)),
 CONSTRAINT tax_attempt_state CHECK(state IN ('sending','sent_test','sent_production','failed','unknown')),
 CONSTRAINT tax_attempt_environment CHECK(environment IN ('test','production'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

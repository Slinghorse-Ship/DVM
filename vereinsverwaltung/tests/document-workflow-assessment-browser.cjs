'use strict';
// Read-only document checks and synthetic session role switches on the gated loopback preview.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require('C:/Users/wehla/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const base = 'http://127.0.0.1:8117/workflows';
const fixture = JSON.parse(fs.readFileSync(path.resolve('.local/document-workflows-20261007/dguv-import.json'),'utf8'));
const doc = fixture.resources.find(row=>row.key==='de-events').document;
assert(/^[a-f0-9]{32}$/.test(doc), 'registered synthetic document id');
const checks = [], errors = [], blocked = [];
const check = (condition, label) => {assert(condition,label);checks.push(label);};
(async()=>{
 const browser = await chromium.launch({headless:true});
 const context = await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
 await context.route('**/*',route=>{
  const url=new URL(route.request().url());
  if(url.origin!==new URL(base).origin){blocked.push(url.href);return route.abort();}
  return route.continue();
 });
 const page=await context.newPage();
 page.on('pageerror',error=>errors.push(error.message));
 try {
  const ready = async()=>{await page.locator('.dwf-risk-sheet').waitFor();};
  const visit = async()=>{const response=await page.goto(base+'?wf_doc='+doc);check(response.status()===200,'risk document HTTP 200');await ready();};
  await visit();
  check(await page.getByRole('heading',{name:'Gefährdungsbeurteilung',exact:true}).count()===1,'module name shown');
  check(await page.getByRole('link',{name:'PDF herunterladen',exact:true}).count()===1,'direct PDF download available');
  check(await page.locator('input[type=file][accept="application/pdf,.pdf"]').count()===1,'PDF attachment picker available to writer');
  const matrix=page.locator('.dwf-register-legend-mini .dwf-register-legend-table');
  check(await matrix.locator('tbody tr').count()===5,'all five severity rows preserved');
  check(await matrix.locator('tbody td').count()===25,'all twenty-five risk scores preserved');
  const size=await matrix.boundingBox();
  check(size.height<=135 && size.width<=180,'numerical matrix compact instead of large block');
  const definitions=page.locator('.dwf-register-axis-definitions');
  check(await definitions.count()===2,'severity and likelihood definitions beside matrix');
  check(await definitions.nth(0).locator('p').count()===5,'all severity explanations retained');
  check(await definitions.nth(1).locator('p').count()===5,'all probability explanations retained');
  check(await page.locator('.dwf-register-band-table tbody tr').count()===3,'all colour meanings retained');
  check(await page.locator('.dwf-risk-sheet details').count()===0,'printed definitions do not require expanding');
  check(!(await page.locator('.dwf-preview-paper').innerText()).includes('Die Vorschau wird nur im Browser'),'no product-progress explanation on document');
  const download=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'PDF herunterladen',exact:true}).click()]);
  const downloadPath=await download[0].path();
  check(fs.readFileSync(downloadPath).subarray(0,5).toString()==='%PDF-','browser PDF download is real PDF');
  const output=path.resolve('output/pdf');fs.mkdirSync(output,{recursive:true});
  await page.locator('.dwf-live-preview').screenshot({path:path.join(output,'gefaehrdungsbeurteilung-vorschau-desktop.png')});
  await page.emulateMedia({media:'print'});
  check(await matrix.isVisible(),'compact matrix remains visible for printing');
  await page.emulateMedia({media:'screen'});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'mobile has no body-level horizontal overflow');
  check((await matrix.boundingBox()).height<=135,'mobile preserves compact matrix');
  const preview=page.locator('.dwf-preview-paper');
  check(await page.locator('.dwf-live-preview').evaluate(n=>n.scrollWidth>n.clientWidth),'wide official document uses bounded horizontal preview scroll');
  await page.locator('.dwf-live-preview').screenshot({path:path.join(output,'gefaehrdungsbeurteilung-vorschau-mobil.png')});
  const role = async value=>{
   await page.locator('.dwf-demo-header select[name=actor]').selectOption(value);
   await Promise.all([page.waitForURL(url=>!url.searchParams.has('wf_doc')),page.getByRole('button',{name:'Rolle wechseln',exact:true}).click()]);
   await visit();
  };
  await role('wf-assignee');
  const edit=page.locator('form input[value="document-workflow-document-save"]').locator('..');
  check(await edit.count()===1 && !(await edit.locator('[name=wf_title]').isDisabled()),'another module writer can edit existing draft');
  await role('wf-reader');
  check(await page.getByRole('button',{name:'Entwurf speichern',exact:true}).count()===0 && await page.locator('[name=wf_title]').isDisabled(),'reader cannot edit or save');
  check(await page.locator('input[type=file]').count()===0,'reader cannot upload attachments');
  check(await page.getByRole('link',{name:'PDF herunterladen',exact:true}).count()===1,'reader can download current PDF');
  check(await matrix.isVisible(),'reader still sees compact matrix');
  const rwe=JSON.parse(fs.readFileSync(path.resolve('.local/document-workflows-20261007/rwe-import.json'),'utf8'));
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base+'?wf_doc='+rwe.document);await page.locator('.dwf-rwe-sheet').waitFor();
  check(await page.locator('.dwf-rwe-metadata tbody tr').count()===7,'RWE source header has document ref, revision, project, equipment, assessors, approver and dates');
  check(await page.locator('.dwf-rwe-matrix tbody tr').count()===5,'RWE matrix five severity levels preserved');
  check(await page.locator('.dwf-rwe-matrix .dwf-rwe-score').count()===25,'RWE matrix twenty-five products preserved');
  check((await page.locator('.dwf-rwe-matrix').innerText()).includes('UMWELT'),'environment axis from source preserved');
  check(await page.locator('.dwf-rwe-matrix tfoot td').count()===6,'all five source frequency ranges retained');
  check(await page.locator('.dwf-rwe-bands tbody tr').count()===3,'all three risk bands in source order');
  check(await page.locator('.dwf-rwe-signatures span').count()===3,'name, date and signature lines retained');
  const legendGap=await page.locator('.dwf-rwe-legend').evaluate(node=>parseFloat(getComputedStyle(node).columnGap));
  check(Math.abs(legendGap-96/25.4)<.02,'RWE matrix legend gap is one millimetre');
  check(await page.locator('.dwf-rwe-metadata thead th').evaluate(node=>getComputedStyle(node).backgroundColor)==='rgb(29, 68, 119)','RWE blue matches source colour');
  check(await page.locator('.dwf-rwe-metadata tbody th').first().evaluate(node=>getComputedStyle(node).backgroundColor)==='rgb(232, 232, 228)','RWE light label grey matches source colour');
  check(await page.locator('.dwf-rwe-metadata tbody tr').last().locator('th').last().evaluate(node=>getComputedStyle(node).backgroundColor)==='rgb(217, 217, 217)','RWE review date grey matches source colour');
  check(await page.locator('.dwf-register-print-table thead th').first().evaluate(node=>getComputedStyle(node).backgroundColor)==='rgb(173, 175, 177)','RWE hazard header grey matches source colour');
  const rweDownload=await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'PDF herunterladen',exact:true}).click()]);
  await rweDownload[0].saveAs(path.join(output,'rwe-gefaehrdungsbeurteilung-deutsch.pdf'));
  check(fs.readFileSync(path.join(output,'rwe-gefaehrdungsbeurteilung-deutsch.pdf')).subarray(0,5).toString()==='%PDF-','RWE-style German form downloads as PDF');
  await page.locator('.dwf-live-preview').screenshot({path:path.join(output,'rwe-gefaehrdungsbeurteilung-desktop.png')});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'RWE form mobile body does not overflow');
  await page.locator('.dwf-live-preview').screenshot({path:path.join(output,'rwe-gefaehrdungsbeurteilung-mobil.png')});
  check(errors.length===0,'no browser JavaScript errors');
  check(blocked.length===0,'no external requests attempted');
  const report={suite:'document-workflow-assessment-browser',status:'passed',checks:checks.length,labels:checks,document:doc,matrix:size,errors,blocked,production_changed:false,finished_at_utc:new Date().toISOString()};
  fs.writeFileSync(path.resolve('audit/document-workflow-assessment-browser-20261008.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
 }finally{await context.close();await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});

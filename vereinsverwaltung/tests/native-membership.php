<?php declare(strict_types=1);
require dirname(__DIR__).'/native/bootstrap.php';
require dirname(__DIR__).'/src/bootstrap.php';
use Kulturhus\Native\TestSupport;
use Kulturhus\Native\Web\Membership;
use Kulturhus\Verein\{Database,MembershipApplications};
$db=TestSupport::db(); Database::migrate($db);
$club='membership-'.bin2hex(random_bytes(6)); $actor='staff-'.bin2hex(random_bytes(6));
$db->prepare('INSERT INTO clubs(id,name) VALUES(?,?)')->execute([$club,'Synthetischer Mitgliedschaftstest']);
$db->prepare("INSERT INTO actors(id,club_id,role,is_superuser) VALUES(?,?,'members',1)")->execute([$actor,$club]);
Database::ensureContributionRates($db);
$staff=new MembershipApplications($db,$club,$actor); $public=new MembershipApplications($db,$club); $view=new Membership($public);
$count=0; $check=static function(bool $ok,string $label)use(&$count){if(!$ok)throw new RuntimeException($label);$count++;};
$csrf=bin2hex(random_bytes(32)); $config=$staff->settings()['config'];
$html=$view->render([],$csrf,false);
$check(str_contains($html,'noch nicht zur Abgabe freigeschaltet'),'manager controls availability');
$config['enabled']=true; $config['fields']['phone']='required'; $staff->saveSettings($config,0);
$html=$view->render([],$csrf,false);
$check(str_contains($html,'name="phone" type="text" required'),'manager fields rendered directly');
$check(str_contains($html,'48,00 €')&&str_contains($html,'72,00 €'),'manager fees rendered');
$check(!str_contains($html,'Kulturhus')&&!str_contains($html,'Jaderberg')&&!str_contains($html,'Wattenmeer'),'generic intake has no foreign cultural club or location copy');
$own=(new Membership($public,['name'=>'Sport & Gemeinschaft <Verein>']))->render([],$csrf,false);
$check(str_contains($own,'Sport &amp; Gemeinschaft &lt;Verein&gt;')&&!str_contains($own,'<Verein>'),'current club name is escaped in the actual membership introduction');
$check(str_contains($own,'48,00 €')&&str_contains($own,'72,00 €')&&str_contains($own,'name="membership_type"'),'own branding retains actual annual fees and original application fields');
$production=$view->render([],$csrf,false,false);
$check(str_contains($production,'Bestätigungsmail anfordern')&&!str_contains($production,'Testantrag absenden'),'production presentation requests the real confirmation rather than claiming test submission');
$post=['csrf'=>$csrf,'request_key'=>bin2hex(random_bytes(16)),'configuration_version'=>'1','first_name'=>'Synthetisch','last_name'=>'Testperson','birthday'=>'1990-01-02','email'=>'synthetic@example.invalid','phone'=>'0000','address'=>'Testweg 1','membership_type'=>'single','consent'=>'1'];
$html=$view->render(array_replace($post,['csrf'=>'wrong']),$csrf,true);
$check(str_contains($html,'role="alert"'),'invalid csrf displayed');
$q=$db->prepare('SELECT COUNT(*) FROM application_confirmations WHERE club_id=?'); $q->execute([$club]);
$check((int)$q->fetchColumn()===0,'invalid csrf writes nothing');
$html=$view->render($post,$csrf,true);
$check(str_contains($html,'Bitte bestätige deinen Mitgliedsantrag'),'native website submits real intake');
$check(str_contains($html,'nicht versendet'),'local delivery honestly disabled');
$production=$view->render($post,$csrf,true,false);
$check(!str_contains($production,'Lokale Testumgebung')&&str_contains($production,'Bitte bestätige deinen Mitgliedsantrag'),'production confirmation does not falsely claim a local disabled transport');
$view->render($post,$csrf,true); $q->execute([$club]);
$check((int)$q->fetchColumn()===1,'repeat submit remains idempotent');
$check(count($staff->applications())===0,'unconfirmed request withheld from board');
$q=$db->prepare('SELECT mail_token FROM application_confirmations WHERE club_id=?');$q->execute([$club]);$token=$q->fetchColumn();
$html=$view->render(['csrf'=>$csrf,'action'=>'confirm-application','confirmation_token'=>$token],$csrf,true);
$check(str_contains($html,'Dein Mitgliedsantrag ist bestätigt'),'confirmation through manager service');
$applications=$staff->applications();
$check(count($applications)===1,'confirmed application visible in same manager');
$check($applications[0]['status']==='pending','no automatic membership acceptance');
$view->render(['csrf'=>$csrf,'action'=>'confirm-application','confirmation_token'=>$token],$csrf,true);
$check(count($staff->applications())===1,'confirmation replay does not duplicate');
$changed=$staff->settings()['config'];$changed['notice_text']='Synthetische neue Hinweise';$staff->saveSettings($changed,1);
$html=$view->render(array_replace($post,['request_key'=>bin2hex(random_bytes(16))]),$csrf,true);
$check(str_contains($html,'Antragsbedingungen wurden geändert'),'stale configuration rejected');
$html=$view->render(array_replace($post,['request_key'=>bin2hex(random_bytes(16)),'first_name'=>'<script>test</script>','configuration_version'=>'2','email'=>'invalid']),$csrf,true);
$check(!str_contains($html,'<script>test</script>')&&str_contains($html,'&lt;script&gt;'),'validation redisplay escapes personal input');
echo json_encode(['suite'=>'native-membership','passed'=>$count,'transport'=>'disabled'],JSON_PRETTY_PRINT).PHP_EOL;

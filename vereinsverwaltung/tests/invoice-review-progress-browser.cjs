'use strict';
// Uses an existing isolated local synthetic invoice. No save, mail or OCR request is made.
const {chromium}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
 const fixturePath=process.env.KULTURHUS_INVOICE_PURPOSE_FIXTURE;
 assert(fixturePath,'Provide the isolated local invoice-purpose fixture.');
 const fixture=JSON.parse(fs.readFileSync(fixturePath,'utf8').replace(/^\uFEFF/,''));
 const base=new URL(fixture.base);assert(['127.0.0.1','localhost','[::1]'].includes(base.hostname),'Local test only.');
 const browser=await chromium.launch({headless:true,channel:'msedge'}),checks=[];
 try{
  const context=await browser.newContext({viewport:{width:1280,height:1000}});
  await context.addCookies([{name:'KH_VEREIN_DEMO',value:fixture.session,url:base.origin+'/'}]);
  const page=await context.newPage(),errors=[],writes=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.method()==='POST'&&!r.url().includes('invoice_accounting_suggestions=1'))writes.push(r.url());});
  const url=base.origin+'/?view=finance&tab=inbox&inbox_doc='+encodeURIComponent(fixture.doc);
  await page.goto(url);
  const form=page.locator('[data-invoice-review-form]');await form.waitFor();
  await page.waitForFunction(()=>document.querySelector('[data-review-check]')?.hidden===false);
  assert.equal(await form.locator('.invoice-review-progress a').count(),3);
  assert.match(await form.locator('[data-review-purpose-status]').innerText(),/Noch auswählen/);
  assert.equal(await form.locator('.invoice-review-positions').evaluate(e=>e.open),true);
  checks.push('Three visible steps and always discoverable position section.');
  const purposeJump=form.locator('[data-review-issues] button').filter({hasText:/^Rechnungszweck$/});
  await purposeJump.click();
  assert.match(await page.evaluate(()=>document.activeElement.getAttribute('aria-label')||document.activeElement.closest('label')?.textContent||''),/Rechnungszweck/);
  checks.push('Missing-field shortcut focuses actual searchable purpose control.');
  await form.locator('[data-purpose-group]').selectOption('general');
  await form.locator('[name=supplier_contact]').selectOption(fixture.supplier);
  await form.locator('[name=description]').fill('Synthetische Rechnung zur Bedienprüfung');
  await form.locator('[name=document_date]').fill('2026-09-08');
  await form.locator('[name=due_date]').fill('2026-09-30');
  await form.locator('[name=amount]').fill('20,00');
  await form.locator('[data-position-add]').click();
  const row=form.locator('[data-position-editor]>fieldset').first();
  await row.locator('[data-field=description]').fill('Synthetische Artikelposition');
  await row.locator('[data-field=amount]').fill('20,00');
  await row.locator('[data-field=tax_rate]').selectOption('0');
  assert.equal(await row.locator('.invoice-position-accounting').evaluate(e=>e.open),true);
  assert.equal(await form.locator('[data-positions-reviewed]').isChecked(),false);
  await page.waitForFunction(()=>document.querySelector('[data-review-accounting-note]').textContent.includes('können offen gespeichert'));
  assert.equal(await form.locator('[data-review-issues] button').count(),1);
  assert.match(await form.locator('[data-review-issues]').innerText(),/Artikel, Preise und Gesamtsumme/);
  checks.push('Only actual review confirmation blocks a complete row; open tax classification is a separate optional notice.');
  await form.locator('[data-positions-reviewed]').check();
  await page.waitForFunction(()=>document.querySelector('[data-review-save-status]').textContent==='Speichern möglich');
  assert.match(await form.locator('[data-review-summary]').innerText(),/noch keine fachliche Prüfung/);
  assert.equal(await form.locator('[data-review-issues]').isVisible(),false);
  checks.push('Explicit review permits save status without claiming approval or performing a save.');
  await row.locator('[data-field=amount]').fill('19,00');
  await page.waitForFunction(()=>document.querySelector('[data-review-save-status]').textContent==='Vorher Angaben ergänzen');
  assert.equal(await form.locator('[data-positions-reviewed]').isChecked(),false);
  checks.push('Changing price removes prior review and exposes the original total mismatch.');
  await row.locator('[data-field=amount]').fill('20,00');
  await row.locator('[data-field=sphere]').selectOption('3');
  await row.locator('[data-field=account]').selectOption(fixture.account);
  await form.locator('[data-purpose-group]').selectOption('insurance');
  await page.waitForTimeout(450);
  assert.equal(await row.locator('[data-field=account]').inputValue(),fixture.account);
  assert.equal(await row.locator('[data-field=sphere]').inputValue(),'3');
  assert.equal(await row.locator('[data-accounting-selected]').innerText(),'Ausgewähltes Steuerkonto: '+await row.locator('[data-field=account]').evaluate(e=>e.selectedOptions[0].textContent));
  assert.equal(await row.locator('[data-field=description]').inputValue(),'Synthetische Artikelposition');
  assert.equal(await form.locator('[data-positions-reviewed]').isChecked(),false);
  checks.push('Purpose changes preserve manual fields and do not automatically confirm review.');
  await row.locator('[data-field=description]').fill('');
  await form.locator('.invoice-review-positions > summary').click();
  const missingArticle=form.locator('[data-review-issues] button').filter({hasText:'Artikel 1 · Beschreibung'});
  await missingArticle.click();
  assert.equal(await form.locator('.invoice-review-positions').evaluate(e=>e.open),true);
  assert.equal(await row.locator('[data-field=description]').evaluate(e=>e===document.activeElement),true);
  await row.locator('[data-field=description]').fill('Synthetische Artikelposition');
  checks.push('A missing position shortcut opens its section and focuses the field.');
  const controls=()=>page.evaluate(()=>[...document.querySelectorAll('[data-invoice-review-form] input:not([type=hidden]):not([type=checkbox]),[data-invoice-review-form] select,[data-invoice-review-form] textarea,[data-invoice-review-form] button,[data-invoice-review-form] summary')].filter(e=>!e.classList.contains('select-search-native')&&e.getClientRects().length).map(e=>({tag:e.tagName,field:e.dataset.field||e.name||e.textContent.slice(0,35),height:e.getBoundingClientRect().height,width:e.getBoundingClientRect().width,font:parseFloat(getComputedStyle(e).fontSize)})));
  assert.deepEqual((await controls()).filter(c=>c.height<44),[],'Every visible field/button has at least44px height.');
  assert.deepEqual((await controls()).filter(c=>c.tag!=='BUTTON'&&c.tag!=='SUMMARY'&&c.width<180),[],'No narrow tiny fields at desktop half-width.');
  assert.deepEqual((await controls()).filter(c=>c.font<16),[],'Visible controls use at least16px text.');
  checks.push('Desktop controls remain at least44px tall and readable at half-screen width.');
  const output=path.dirname(fixturePath);
  await form.scrollIntoViewIfNeeded();await page.screenshot({path:path.join(output,'invoice-review-desktop.png'),fullPage:false});
  await row.locator('.invoice-position-accounting').scrollIntoViewIfNeeded();await page.screenshot({path:path.join(output,'invoice-review-accounting.png'),fullPage:false});
  await page.setViewportSize({width:390,height:844});
  await row.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'No horizontal page scrolling on390px.');
  assert.deepEqual((await controls()).filter(c=>c.height<44),[],'Mobile controls remain44px.');
  await page.locator('.invoice-mobile-switch a[href="#invoice-original"]').click();
  assert.equal(new URL(page.url()).hash,'#invoice-original');
  await page.locator('.invoice-mobile-switch a[href="#rechnung-erfassen"]').click();
  assert.equal(new URL(page.url()).hash,'#rechnung-erfassen');
  await page.screenshot({path:path.join(output,'invoice-review-mobile.png'),fullPage:false});
  checks.push('Mobile has no horizontal overflow and retains the original/form switch.');
  await row.locator('[data-field=description]').fill('');await row.locator('[data-field=amount]').fill('');await row.locator('[data-field=tax_rate]').selectOption('');
  await page.waitForFunction(()=>document.querySelectorAll('[data-review-issues] button').length>=4);
  await page.evaluate(()=>{document.querySelector('[data-position-editor]>fieldset .invoice-position-remove').click();document.querySelector('[data-position-add]').click();});
  await form.locator('[data-review-issues] button').filter({hasText:'Artikel 1 · Beschreibung'}).click();
  assert.equal(await form.locator('[data-position-editor]>fieldset [data-field=description]').evaluate(e=>e===document.activeElement),true);
  checks.push('Replacing a position with identical missing labels updates shortcuts to the new controls.');
  assert.deepEqual(errors,[]);assert.deepEqual(writes,[]);
  checks.push('No JavaScript failures, writes, OCR calls or mail requests.');
  const without=await browser.newContext({javaScriptEnabled:false,viewport:{width:1280,height:1000}});
  await without.addCookies([{name:'KH_VEREIN_DEMO',value:fixture.session,url:base.origin+'/'}]);
  const plain=await without.newPage();await plain.goto(url);
  assert.equal(await plain.locator('[name=purpose]').isVisible(),true);
  assert.equal(await plain.locator('[data-invoice-save]').isVisible(),true);
  assert.equal(await plain.locator('.invoice-review-positions').evaluate(e=>e.open),true);
  checks.push('No-script form retains purpose, visible positions entry and explicit save.');
  console.log(JSON.stringify({passed:checks.length,checks},null,2));
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});

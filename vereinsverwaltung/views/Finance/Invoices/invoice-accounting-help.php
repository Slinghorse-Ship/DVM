    <summary>Kleine Hilfe: Sphäre, Steuerkonto und BU</summary>
    <p>Gehen Sie je Position in dieser Reihenfolge vor:</p>
    <dl>
        <dt>1. Sphäre – wofür wird es verwendet?</dt>
        <dd>Wählen Sie den Vereinsbereich, zu dem diese Ausgabe tatsächlich gehört. Ein Bühnenpodest erhält seine Sphäre durch die Verwendung; „Inventar“ allein legt sie nicht fest.</dd>
        <dt>2. Steuerkonto – was wurde gekauft?</dt>
        <dd>Suchen Sie nach der Art der Ausgabe, zum Beispiel Honorar, Versicherung oder Porto. Das Steuerkonto ist ein Buchhaltungskonto, keine IBAN. Bei Anschaffungen muss zusätzlich geklärt sein, ob Aufwand oder Anlagevermögen vorliegt.</dd>
        <dt>3. BU-Schlüssel – wie wird die Umsatzsteuer behandelt?</dt>
        <dd>BU bedeutet Buchungsschlüssel. Er steuert eine zusätzliche Umsatzsteuerbehandlung im Export. „19 %“ auf einer Rechnung ist kein Grund, automatisch einen Vorsteuerschlüssel zu wählen. Ohne passenden Sonderfall bleibt die Auswahl „Ohne gesonderten Schlüssel“.</dd>
        <dt>Vorsteuerabzug gesondert prüfen</dt>
        <dd>Bei „Kein Vorsteuerabzug“ bleibt die Steuer laut Rechnung erhalten, der Bruttobetrag bleibt Kosten oder Gegenstandswert und der BU-Schlüssel bleibt leer. „Noch klären“ erlaubt das Speichern, verlangt bei steuerhaltigen Ausgaben aber Nacharbeit vor dem DATEV-Export. Die Vorauswahl kommt aus den Steuereinstellungen; jede Position kann davon abweichen.</dd>
    </dl>
    <h3>Welche Sphäre passt?</h3>
    <p>Diese Bezeichnungen finden Sie in der Auswahl. Entscheidend ist die tatsächliche Tätigkeit des Vereins.</p>
    <dl>
        <dt>1 · Ideeller Bereich</dt>
        <dd>Gemeinsame Vereinsarbeit ohne Verkauf einer Leistung, zum Beispiel echte Mitgliedsbeiträge und Spenden.</dd>
        <dt>2 · Vermögensverwaltung</dt>
        <dd>Zum Beispiel Zinsen oder eine längerfristige Vermietung; die konkrete Tätigkeit entscheidet.</dd>
        <dt>3 · Zweckbetrieb</dt>
        <dd>Wirtschaftliche Tätigkeit, die unter den steuerlichen Voraussetzungen unmittelbar dem gemeinnützigen Zweck dient. Eine Kulturveranstaltung ist nicht allein wegen ihres Namens automatisch ein Zweckbetrieb.</dd>
        <dt>4 · Wirtschaftlicher Geschäftsbetrieb</dt>
        <dd>Wirtschaftliche Tätigkeit außerhalb eines Zweckbetriebs, zum Beispiel gesonderte Werbung für einen Sponsor.</dd>
        <dt>9 · Sammelposten</dt>
        <dd>Technische Sammelzuordnung im Kontenplan. Sie ersetzt keine noch ungeklärte Sphäre.</dd>
    </dl>
    <p><strong>Mehrere Zwecke?</strong> Prüfen Sie die Positionen einzeln. Eine Aufteilung muss zum Original und zur tatsächlichen Nutzung passen. Der Gesamtbetrag darf sich dabei nicht ändern.</p>
    <p><strong>Noch unsicher?</strong> Lassen Sie Sphäre und Steuerkonto gemeinsam offen. Sie können die Rechnung speichern; der Kassenwart klärt die Kontierung vor dem Export.</p>

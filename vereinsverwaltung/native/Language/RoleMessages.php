    public static function key(string $source):string{return'roles_'.substr(hash('sha256',$source),0,24);}
    public static function messages(string $locale):array
    {
        $english=explode('-',$locale,2)[0]==='en';$out=[];
        foreach(self::ENGLISH as$source=>$translation)$out[self::key($source)]=$english?$translation:$source;return$out;
    }
    public static function text(string $source,array $messages):string{return$messages[self::key($source)]??ManagerMessages::text($source,$messages);}

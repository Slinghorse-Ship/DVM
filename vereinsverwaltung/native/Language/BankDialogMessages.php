    public static function key(string $source):string{return 'bank_dialog_'.substr(hash('sha256',$source),0,24);}
    public static function messages(string $locale):array
    {
        $en=explode('-',$locale,2)[0]==='en';$out=[];
        foreach(self::ENGLISH as $source=>$translation)$out[self::key($source)]=$en?$translation:$source;return $out;
    }
    public static function text(string $source,array $messages,array $values=[]):string
    {
        $text=$messages[self::key($source)]??TransferMessages::text($source,$messages);
        foreach($values as $key=>$value)$text=str_replace('{'.$key.'}',(string)$value,$text);return $text;
    }

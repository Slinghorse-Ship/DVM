 {
  $out=[];foreach(self::ENGLISH as$de=>$en)$out[ManagerMessages::key($de)]=$locale==='en'?$en:$de;return$out;
 }
 public static function text(string $source,array $messages,array $values=[]):string
 {
  $text=ManagerMessages::text($source,$messages);
  return preg_replace_callback('/\{([a-z_]+)\}/',static fn(array $m):string=>array_key_exists($m[1],$values)?(string)$values[$m[1]]:$m[0],$text)??$text;
 }

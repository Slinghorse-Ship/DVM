    public static function key(string $source):string{return 'video_recovery_'.substr(hash('sha256',$source),0,24);}
    public static function messages(string $locale):array{$english=explode('-',$locale,2)[0]==='en';$out=[];foreach(self::ENGLISH as$source=>$translation)$out[self::key($source)]=$english?$translation:$source;return$out;}
    public static function text(string $source,array $messages,array $values=[]):string{$text=$messages[self::key($source)]??VideoInventoryMessages::text($source,$messages);$tokens=[];foreach($values as$key=>$value)$tokens['{'.$key.'}']=(string)$value;return strtr($text,$tokens);}
    public static function browser(array $messages):array{$out=VideoFileMessages::browser($messages);foreach(VideoInventoryMessages::ENGLISH+self::ENGLISH as$source=>$translation)$out[$source]=self::text($source,$messages);return$out;}

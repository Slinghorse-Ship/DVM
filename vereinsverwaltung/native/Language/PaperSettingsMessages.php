    public static function key(string $source):string{return 'paper_settings_'.substr(hash('sha256',$source),0,24);}
    public static function messages(string $locale):array
    {$en=explode('-',$locale,2)[0]==='en';$out=[];foreach(self::ENGLISH as$source=>$translation)$out[self::key($source)]=$en?$translation:$source;return$out;}
    public static function text(string $source,array $messages):string
    {
        if(isset($messages[self::key($source)]))return$messages[self::key($source)];
        foreach(\Kulturhus\Verein\SettingsSchema::fields('paper')as$field)if(str_starts_with($source,$field[0].': '))return self::text($field[0],$messages).': '.self::text(substr($source,strlen($field[0])+2),$messages);
        if(preg_match('/\AZahl zwischen ([0-9]+) und ([0-9]+) erforderlich\.\z/D',$source,$m))return strtr(self::text('Zahl zwischen {min} und {max} erforderlich.',$messages),['{min}'=>$m[1],'{max}'=>$m[2]]);
        foreach([MailSettingsMessages::class,DocumentMessages::class]as$class){$key=$class::key($source);if(isset($messages[$key]))return$messages[$key];}
        return GeneralSettingsMessages::text($source,$messages);
    }

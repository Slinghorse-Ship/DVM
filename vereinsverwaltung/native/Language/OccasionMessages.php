 public static function key(string $source):string{return 'occasion_'.substr(hash('sha256',$source),0,24);}
 public static function messages(string $locale):array{$en=explode('-',$locale,2)[0]==='en';$out=[];foreach(self::ENGLISH as$source=>$english)$out[self::key($source)]=$en?$english:$source;return$out;}
 public static function text(string $source,array $messages=[],array $values=[]):string
 {
  $text=$messages[self::key($source)]??$source;
  return preg_replace_callback('/\{([a-z_]+)\}/',static fn($m)=>array_key_exists($m[1],$values)?(string)$values[$m[1]]:$m[0],$text);
 }

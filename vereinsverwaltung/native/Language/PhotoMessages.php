 public static function key(string $source):string{return 'photo_ui_'.substr(hash('sha256',$source),0,24);}
 public static function messages(string $locale):array
 {
  $english=explode('-',$locale,2)[0]==='en';$out=[];foreach(self::ENGLISH as$source=>$value)$out[self::key($source)]=$english?$value:$source;return$out;
 }
 public static function text(string $source,array $messages):string{return isset(self::ENGLISH[$source])?($messages[self::key($source)]??$source):ManagerMessages::text($source,$messages);}
}

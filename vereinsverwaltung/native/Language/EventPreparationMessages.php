    public static function key(string $source): string { return 'event_preparation_'.substr(hash('sha256', $source), 0, 24); }
    public static function messages(string $locale): array
    {
        $english = explode('-', $locale, 2)[0] === 'en'; $result = [];
        foreach (self::ENGLISH as $source=>$translation) $result[self::key($source)] = $english ? $translation : $source;
        return $result;
    }
    public static function text(string $source, array $messages): string
    {
        return $messages[self::key($source)] ?? $messages[SocialPlanningMessages::key($source)] ?? $messages[VideoStudioMessages::key($source)] ?? ManagerMessages::text($source, $messages);
    }

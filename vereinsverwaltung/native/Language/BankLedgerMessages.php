    public static function key(string $source):string{return 'bank_ledger_'.substr(hash('sha256',$source),0,24);}
    public static function messages(string $locale):array
    {
        $english=explode('-',$locale,2)[0]==='en';$messages=[];
        foreach(self::ENGLISH as $source=>$translation)$messages[self::key($source)]=$english?$translation:$source;
        return $messages;
    }
    public static function text(string $source,array $messages,array $values=[]):string
    {
        $text=$messages[self::key($source)]??$source;
        if(preg_match('/\A([0-9]+) Umsätze dieser Seite eindeutig zugeordnet\. Übrige Umsätze bitte manuell prüfen\.\z/D',$source,$parts)){
            $text=$messages[self::key('{count} Umsätze dieser Seite eindeutig zugeordnet. Übrige Umsätze bitte manuell prüfen.')]??$source;
            $values['count']=$parts[1];
        }
        foreach(['Kontoart und Anfangsbestand sind geschützt: ','Dieses Konto wird bereits verwendet und kann nur deaktiviert werden: '] as $prefix){
            if(str_starts_with($source,$prefix)&&str_ends_with($source,'.')){
                $reasons=explode('; ',substr($source,strlen($prefix),-1));
                if(array_filter($reasons,static fn($reason)=>!isset(self::ENGLISH[$reason]))===[]){
                    $text=$messages[self::key($prefix.'{reasons}.')]??$prefix.'{reasons}.';
                    $values['reasons']=implode('; ',array_map(static fn($reason)=>self::text($reason,$messages),$reasons));
                }
            }
        }
        return strtr($text,array_combine(array_map(static fn($key)=>'{'.$key.'}',array_keys($values)),array_values($values)));
    }

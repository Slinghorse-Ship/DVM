 public static function manifest():array
 {
  $assets=[];
  foreach(self::FILES as $file){
   $path=dirname(__DIR__, 1).'/../public/'.$file;
   if(!is_file($path))throw new \RuntimeException('Registered manager asset missing.');
   $assets[$file]=['url'=>$file.'?v='.substr(hash_file('sha256',$path),0,16),'kind'=>str_ends_with($file,'.css')?'style':'script','module'=>in_array($file,['application-pdf.js','preview-pan.js','system-status.js'],true)];
  }
  if(getenv('KH_NATIVE_MANAGER')==='1'){
   require_once dirname(__DIR__, 1).'/../native/bootstrap.php';
   foreach(\Kulturhus\Native\Integration\Assets::sources() as $file=>$path){
    if(!is_file($path))throw new \RuntimeException('Native manager asset missing.');
    $assets[$file]=['url'=>$file.'?v='.substr(hash_file('sha256',$path),0,16),'kind'=>str_ends_with($file,'.css')?'style':'script','module'=>\Kulturhus\Native\Web\BootstrapAssets::isModule($file)];
   }
  }
  return $assets;
 }
 /** Load registered module styles before the first paint, preserving their cascade order. */
 public static function versionHtml(string $html,array $assets):string
 {
  $html=preg_replace_callback('/(<(?:script|link)\b[^>]*?\s(?:src|href)=")([a-zA-Z0-9.-]+\.(?:js|css))(?:\?[^"<>]*)?("[^>]*>)/i',static function(array $m)use($assets):string{
   return isset($assets[$m[2]])?$m[1].htmlspecialchars($assets[$m[2]]['url'],ENT_QUOTES,'UTF-8').$m[3]:$m[0];
  },$html);
  $parts=preg_split('/(<body\b[^>]*>)/i',$html,2,PREG_SPLIT_DELIM_CAPTURE);
  if(count($parts)!==3||!str_contains($parts[0],'</head>'))return $html;
  $registered=[];foreach($assets as$asset)if(($asset['kind']??null)==='style')$registered[htmlspecialchars($asset['url'],ENT_QUOTES,'UTF-8')]=true;
  $styles='';$body=preg_replace_callback('/<link\b(?=[^>]*\brel="stylesheet")[^>]*\bhref="([^"]+)"[^>]*>/i',static function(array$m)use($registered,&$styles):string{if(!isset($registered[$m[1]]))return$m[0];$styles.=$m[0];return '';},$parts[2]);
  return str_replace('</head>',$styles.'</head>',$parts[0]).$parts[1].$body;
 }
